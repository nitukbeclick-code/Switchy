// ────────────────────────────────────────────────────────────────────────────
// check-cta-contrast.mjs — the primary CTA's label must clear WCAG AA in BOTH
// themes, measured on the FINAL COMPUTED style, not on what the source says.
//
// WHY THIS EXISTS: styles.css declares .btn--primary / .plan__cta near the top
// with an AA-safe ground, and then a 2026-07 editorial re-skin layer ~4300
// lines further down restates `background` at the SAME specificity. Later
// source order wins, so the re-skin silently replaced the safe fill with
// `var(--accent)` — which the dark theme lifts to a bright mint (#5DD6AB).
// White-on-mint is 1.80:1 against a 4.5:1 floor, and it hit every hero CTA,
// every plan-card CTA and the lead-form submit on 269 lead-bearing pages.
// Reading the CSS could not catch that; only resolving the whole cascade could.
//
// So this does not parse CSS. It loads a real page in Chromium under each
// prefers-color-scheme, reads getComputedStyle off real buttons, pulls the
// colour stops out of the resolved background (compositing translucent fills
// over their ancestors), and computes the contrast ratio against the resolved
// label colour. Hover states are measured too — a hover background hardcoded to
// #fff is the same bug wearing a different hat.
//
// USAGE
//   node scripts/check-cta-contrast.mjs                 # cellular.html + index.html
//   node scripts/check-cta-contrast.mjs /guides.html
// Exit code 1 if anything lands below AA. Set PW_CHROMIUM to override the
// browser path. Serves site/ directly, and maps styles.min.css → styles.css so
// an un-rebuilt source edit is what actually gets measured.
// ────────────────────────────────────────────────────────────────────────────

import { chromium } from "playwright";
import { createServer } from "node:http";
import { readFile, stat } from "node:fs/promises";
import { extname, join, normalize, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "site");
const PORT = Number(process.env.PORT || 4401);
// Let Playwright launch the browser IT provisioned for its own version. The
// default used to be a hardcoded /opt/pw-browsers/chromium-1194 path — the
// browser of ONE development sandbox, pinned to one build number — which is the
// whole reason this script could never run anywhere else, CI included.
// PW_CHROMIUM still overrides, for an environment that supplies its own binary.
const CHROMIUM = process.env.PW_CHROMIUM || undefined;

const AA = 4.5; // normal-size text; every CTA label on this site is <18.66px bold
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".webp": "image/webp",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".woff2": "font/woff2",
};

/** The selectors whose label sits on a themed fill, plus the states that matter. */
const TARGETS = [
  { sel: ".btn--primary", states: ["base", "hover"] },
  { sel: ".plan__cta", states: ["base", "hover"] },
  { sel: ".btn--ghost", states: ["base", "hover"] },
];
const PAGES = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ["/cellular.html", "/index.html"];

const serve = () =>
  createServer(async (req, res) => {
    try {
      const url = decodeURIComponent((req.url || "/").split("?")[0]);
      // The committed styles.min.css is generated by the rebuild cron and lags
      // the hand-edited source; measure the SOURCE or this proves nothing.
      const file = url.endsWith("styles.min.css") ? "/styles.css" : url;
      let p = normalize(join(ROOT, file === "/" ? "/index.html" : file));
      if (!p.startsWith(ROOT)) return void res.writeHead(403).end();
      if ((await stat(p)).isDirectory()) p = join(p, "index.html");
      res.writeHead(200, {
        "content-type": TYPES[extname(p)] ?? "application/octet-stream",
      });
      res.end(await readFile(p));
    } catch {
      res.writeHead(404).end("not found");
    }
  });

// ── WCAG 2.x relative luminance + contrast ratio ────────────────────────────
const chan = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const lum = ([r, g, b]) => 0.2126 * chan(r) + 0.7152 * chan(g) + 0.0722 * chan(b);
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const hex = ([r, g, b]) =>
  "#" + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

/**
 * Read the resolved paint of one element: the label colour, and every colour
 * stop of its background (a gradient contributes ALL its stops — a label is
 * only as legible as the worst pixel it sits on). Translucent stops are
 * composited over the nearest opaque ancestor background, because that is what
 * the eye actually sees.
 */
const PROBE = (selector) => {
  const el = document.querySelector(selector);
  if (!el) return null;

  // Chromium serialises a resolved `color-mix(…, transparent)` as
  // `color(srgb 1 0.988 0.965 / 0.82)` — 0–1 channels, NOT 0–255. Reading those
  // as rgb() turns a near-white fill into near-black and invents failures, so
  // normalise both notations to [r,g,b (0–255), a (0–1)].
  const parse = (s) => {
    if (!s || s === "transparent" || s === "none") return [0, 0, 0, 0];
    const raw = s.match(/-?[\d.]+%?/g) || [];
    if (raw.length < 3) return [0, 0, 0, 0];
    const n = raw.map((t) => (t.endsWith("%") ? parseFloat(t) / 100 : parseFloat(t)));
    const unit = /^color\(/i.test(s) || raw[0].endsWith("%") ? 255 : 1;
    return [n[0] * unit, n[1] * unit, n[2] * unit, n[3] === undefined ? 1 : n[3]];
  };

  const cs = getComputedStyle(el);

  // Nearest opaque ancestor background — the ground a translucent fill sits on.
  let under = [255, 255, 255, 1];
  for (let n = el.parentElement; n; n = n.parentElement) {
    const p = parse(getComputedStyle(n).backgroundColor);
    if (p[3] === 1) {
      under = [p[0], p[1], p[2], 1];
      break;
    }
  }
  const over = (c) => [0, 1, 2].map((i) => c[i] * c[3] + under[i] * (1 - c[3]));

  const stops = [];
  const img = cs.backgroundImage;
  if (img && img !== "none") {
    for (const m of img.matchAll(/(?:rgba?|color)\([^)]*\)/gi)) stops.push(over(parse(m[0])));
  }
  const bg = parse(cs.backgroundColor);
  if (!stops.length || bg[3] > 0) stops.push(over(bg));

  // FILTER IS NOT PART OF backgroundImage — and it repaints the resolved fill
  // AFTER the cascade, so a checker that stops at the declared stops reports a
  // ratio the user never sees. That blind spot shipped once already: a
  // `filter: brightness(1.06)` hover on .plan__cta took a 4.91:1 dark ground to
  // 4.44:1 while this script printed a clean pass. Model what we can, and REFUSE
  // to guess at what we cannot — an unmodelled filter returns a flag that main()
  // turns into a hard failure, never a silent green.
  const filter = cs.filter && cs.filter !== "none" ? cs.filter : "";
  let unmodelled = "";
  const applyFilter = (c) => {
    if (!filter) return c;
    let out = c.slice(0, 3);
    for (const fn of filter.matchAll(/([a-z-]+)\(([^)]*)\)/gi)) {
      const [, name, arg] = fn;
      const n = arg.trim().endsWith("%") ? parseFloat(arg) / 100 : parseFloat(arg);
      if (name === "brightness" && Number.isFinite(n)) {
        out = out.map((v) => Math.min(255, Math.max(0, v * n)));
      } else if (name === "opacity" && Number.isFinite(n)) {
        out = [0, 1, 2].map((i) => out[i] * n + under[i] * (1 - n));
      } else if (name === "grayscale" && n === 0) {
        /* no-op */
      } else {
        unmodelled = `${name}(${arg})`;
      }
    }
    return out;
  };

  return {
    label: applyFilter(over(parse(cs.color))),
    stops: stops.map(applyFilter),
    filter,
    unmodelled,
    text: el.textContent.trim().slice(0, 24),
  };
};

async function main() {
  const server = serve();
  await new Promise((r) => server.listen(PORT, r));
  const browser = await chromium.launch({ executablePath: CHROMIUM });
  const rows = [];

  try {
    for (const path of PAGES) {
      for (const dark of [false, true]) {
        const ctx = await browser.newContext({
          viewport: { width: 1280, height: 900 },
          colorScheme: dark ? "dark" : "light",
          locale: "he-IL",
        });
        const page = await ctx.newPage();
        await page.goto(`http://127.0.0.1:${PORT}${path}`, { waitUntil: "networkidle" });
        await page.waitForTimeout(600);

        for (const { sel, states } of TARGETS) {
          const el = page.locator(sel).first();
          if (!(await el.count())) continue;
          for (const state of states) {
            if (state === "hover") {
              await el.scrollIntoViewIfNeeded().catch(() => {});
              await el.hover({ force: true }).catch(() => {});
              await page.waitForTimeout(250);
            }
            const probe = await page.evaluate(PROBE, sel);
            if (!probe) continue;
            for (const stop of probe.stops) {
              rows.push({
                page: path,
                theme: dark ? "dark" : "light",
                sel,
                state,
                fill: hex(stop),
                label: hex(probe.label),
                cr: ratio(probe.label, stop),
                unmodelled: probe.unmodelled,
              });
            }
            await page.mouse.move(0, 0);
            await page.waitForTimeout(120);
          }
        }
        await ctx.close();
      }
    }
  } finally {
    await browser.close();
    server.close();
  }

  const pad = (s, n) => String(s).padEnd(n);
  console.log(
    `\n${pad("page", 16)}${pad("theme", 7)}${pad("selector", 15)}${pad("state", 7)}` +
      `${pad("fill", 10)}${pad("label", 10)}ratio`,
  );
  console.log("─".repeat(78));
  let worst = Infinity;
  // Collapse identical measurements: 59 .plan__cta on a page all paint the same.
  const seen = new Set();
  for (const r of rows) {
    const key = [r.page, r.theme, r.sel, r.state, r.fill, r.label].join("|");
    if (seen.has(key)) continue;
    seen.add(key);
    const ok = r.cr >= AA;
    worst = Math.min(worst, r.cr);
    console.log(
      pad(r.page, 16) + pad(r.theme, 7) + pad(r.sel, 15) + pad(r.state, 7) +
        pad(r.fill, 10) + pad(r.label, 10) + r.cr.toFixed(2) + ":1  " + (ok ? "✓" : "✗ FAILS AA"),
    );
  }
  const failed = rows.filter((r) => r.cr < AA);
  // A filter this script cannot model is NOT a pass — it is an unknown, and an
  // unknown reported as green is exactly how the hover bug survived the first
  // run of this gate. Fail loudly and name the function so it can be added.
  const blind = [...new Set(rows.filter((r) => r.unmodelled).map((r) => r.unmodelled))];
  console.log("─".repeat(78));
  for (const f of blind) {
    console.log(`✗ UNMODELLED FILTER \`${f}\` — this script cannot compute the painted`);
    console.log("  colour through it. Add it to applyFilter() or the number above is a guess.");
  }
  console.log(
    failed.length
      ? `✗ ${failed.length} measurement(s) below AA ${AA}:1 — worst ${worst.toFixed(2)}:1`
      : `✓ all CTA labels clear AA ${AA}:1 in both themes — worst ${worst.toFixed(2)}:1`,
  );
  process.exit(failed.length || blind.length ? 1 : 0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
